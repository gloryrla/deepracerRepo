"""
[최종 채택 모델] D-speedup-clone

콘솔: /models/r58VqnOQYgCIgy7
트랙: A to Z Speedway - **Counterclockwise**
학습: 15분 (D-speedup에서 Clone)
알고리즘: PPO · Batch 64 · Epochs 3 · Discount 0.995
         LR 0.0003 · Entropy 0.01 · Huber · Episodes 20

액션 스페이스 (10행, ±20도 제한, 최고 2.60):

        -20/1.30  -14/1.60   -8/2.00   -3/2.30    0/2.60
          3/2.30    8/2.00   14/1.60   20/1.30    0/2.00

======================================================================
                          왜 이 코드인가
======================================================================

이 파일에는 **좌표가 한 줄도 없다.** 그것이 이 모델이 채택된 이유다.

우리의 첫 접근은 반대였다. 트랙이 미리 정해져 있으므로 최적 경로(인코스)를
계산해 좌표로 학습시키는 것이 정답이라고 판단했다. 곡률 균등화(K1999)로
센터라인 16.635 m를 15.409 m로 7.4% 단축한 궤적을 구했고, 각 점의 목표속도까지
물리 계산으로 붙여 레인 B와 E를 만들었다.

**시뮬레이터에서는 그 가설이 맞았다.**

        레인 E (좌표 + 목표속도)   7.473초   탈선 0   편차 0.086
        레인 C (곡률 기반 속도)    9.283초   탈선 0   편차 0.408
        레인 A (중앙선)            9.501초   탈선 1   편차 1.003
        레인 D (중앙선 + 워블억제) 9.698초   탈선 1   편차 1.104

정보량이 많은 보상이 그대로 순위였다. E > C > A > D.

**실차에서는 이 순위가 뒤집혔다.** 좌표 기반 모델(B·E)은 트랙 반대쪽으로 계속
이탈했고, 가장 느렸던 D가 유일하게 안정적으로 완주했다.

----------------------------------------------------------------------
원인 1. 여유폭이 카메라 레이턴시를 못 버틴다
----------------------------------------------------------------------

최적 경로는 흰선에서 0.180 m 떨어져 달린다. 센터라인은 0.439 m다.
카메라 지연 동안 차는 계속 굴러가므로 그만큼 늦게 반응한다.

        지연 100 ms, 속도 2.0 m/s  ->  0.20 m 밀림
            최적 경로: 여유 0.180 m 의 111 퍼센트  = 초과
            센터라인 : 여유 0.439 m 의  46 퍼센트

**지연 100 ms와 2.0 m/s만 되어도 최적 경로의 여유가 전부 사라진다.**
시뮬레이터에는 지연이 없으므로 0.180 m는 충분한 값이었다. 실차에서는 아니었다.

----------------------------------------------------------------------
원인 2. 보상이 요구한 과제 자체가 달랐다 (더 근본적)
----------------------------------------------------------------------

        센터라인 보상  ->  "차선을 화면 중앙에 놓아라"      (국소 · 상대 · 대칭)
        좌표 보상      ->  "내가 트랙의 몇 번째 지점인지
                            알아내고 거기서 인쪽에 붙어라"  (전역 · 절대 위치)

좌표 보상은 정책에게 **자기위치 추정**이라는 훨씬 어려운 지각 문제를 강요한다.
그리고 정책이 그것을 푸는 수단은 카메라 픽셀뿐이므로, 시뮬레이터의 배경과
텍스처 같은 **시뮬 고유 단서를 외워서** 해결한다. 실제 트랙에는 그 단서가 없다.

반면 센터라인 보상이 요구하는 "차선 경계가 화면 어디 있나"는 실차에도 그대로
존재하는 단서다. 그래서 전이된다.

**"보상에 정보를 많이 주면 좋다"가 시뮬에서는 맞고 실차에서는 틀린 이유가
이것이다. 정보가 많은 보상은 전이되지 않는 능력을 요구했다.**

======================================================================
                        코드 각 항의 설계 의도
======================================================================

--- 위치 항: exp(-4.0 * (d/tw)^2) ---

`distance_from_center`는 중앙선 기준 좌우 편차다. **절대 좌표가 아니라 상대량**
이므로 카메라가 직접 보는 값이고 지연에 둔감하다. 트랙 폭으로 나누므로 트랙이
바뀌어도 의미가 유지되고, 수정할 값이 없다.

가우시안(제곱)을 쓴 이유는 d=0 근처가 평평하기 때문이다. 중앙에서 1~2 cm
벗어난 것을 거의 벌주지 않아서, 밀리미터를 쫓느라 조향을 떠는 정책이 되는 것을
막는다. 계수 4.0은 레인 B/E의 6.0보다 느슨하다. 실차에서는 라인을 정확히
따라가는 것보다 여유를 갖는 것이 중요하다는 판단이다.

--- 조향 변화율 항: rate > 15 -> 0.5, rate > 8 -> 0.8 ---

이 모델의 핵심 항이다. 시뮬레이터는 서보 지연과 타이어 슬립을 모델링하지
않으므로, 조향을 좌우로 튕기는 정책도 시뮬에서는 멀쩡해 보인다. 실차에서는
접지를 잃고 스핀한다.

보상 함수는 이전 스텝을 기억하지 못하므로 직전 조향각을 모듈 전역 `PREV`에
둔다. 롤아웃 워커가 여러 개면 값이 섞일 수 있는 기법이지만, 실측에서 문제가
관측되지 않았고 얻는 안정성이 컸다.

액션 스페이스가 이 항과 함께 설계되었다. 인접 액션 간 조향 차이가 3~6도이므로
(-20 -> -14 는 6) 점진적으로 꺾으면 페널티가 없고, -20 에서 0 으로 튕기면
rate=20 으로 0.5배를 받는다. **즉 "부드럽게 꺾어라"가 액션 수준에서 강제된다.**

--- 고속 대각도 항: speed > 1.9 and |steer| > 15 -> 0.7 ---

정직하게 말하면 **최종 액션 스페이스에서 이 항은 발동하지 않는다.**
±20도가 1.30 m/s와, ±14도가 1.60 m/s와 묶여 있어 어느 것도 1.9를 넘지 않는다.

이것은 실패가 아니라 설계가 수렴한 결과다. 보상으로 소프트하게 억제하려던
것을 **액션 스페이스가 하드하게 보장**하게 되었다. 보상 항은 안전망으로 남겨
두었다.

--- 이탈 시 1e-3 (0이 아닌 이유) ---

0으로 두면 그 스텝의 기울기가 사라져 학습 신호가 끊긴다. 아주 작은 양수로
두면 가능한 모든 트랙 위 상태보다 확실히 나쁘지만 학습은 계속된다.

======================================================================
                    액션 스페이스: ±20도가 상한인 이유
======================================================================

코너에서 날아가는 것을 막으려고 조향각을 25, 30도까지 올려 시도했다.
**더 큰 조향이 더 나은 코너링을 준다는 추측은 실차에서 틀렸다.**

    1. 바퀴가 헛돌았다. 자전거 모델로 30도는 회전반경 0.286 m이고 0.6g
       기준 한계속도가 1.30 m/s다. 그보다 빠르면 아무리 꺾어도 접지를 잃고
       밖으로 밀려나간다. 조향을 더 넣는 것이 해결이 아니었다
    2. 직진 구간에서 좌우로 왔다갔다하며 잃는 시간이 코너에서 얻는 것보다
       컸다. 큰 조향 액션이 존재하는 것만으로 정책이 그것을 쓰기 때문이다

**20도가 코너를 가장 잘 소화하는 지점이었고, 그 각도에서는 속도를 낮추고
직진 구간에서 속도를 올리는 것이 정답이었다.** 액션 스페이스의
`±20/1.30` 과 `0/2.60` 이 그 결론이다.

각도별 물리 한계 (축간거리 0.165 m, 0.6g 가정):

         조향각   회전반경   한계속도
           8도    1.174 m    2.63 m/s
          14도    0.662 m    1.97 m/s
          20도    0.453 m    1.63 m/s
          30도    0.286 m    1.30 m/s

액션 스페이스의 속도가 이 표를 따라간다. `20/1.30`은 한계 1.63보다 낮게 잡아
실차 접지력이 가정보다 나쁠 경우를 흡수한다.
"""
import math

# 직전 스텝의 조향각. 보상 함수는 이전 스텝을 기억하지 못하므로 모듈 전역에 둔다
PREV = {'steer': 0.0}


def reward_function(params):
    steer = params['steering_angle']

    # 에피소드 시작 시 이전 에피소드의 잔값을 지운다.
    # 이게 없으면 첫 스텝에서 엉뚱한 변화율이 계산된다
    if params['steps'] <= 1:
        PREV['steer'] = steer

    if params['is_offtrack'] or not params['all_wheels_on_track']:
        PREV['steer'] = steer
        return 1e-3

    tw = params['track_width']
    d = params['distance_from_center']
    speed = params['speed']

    # 중앙선까지의 거리. 절대 좌표가 아닌 상대량이라 카메라 지연에 강건하다.
    # 폭으로 정규화하므로 트랙이 바뀌어도 수정할 값이 없다
    reward = math.exp(-4.0 * (d / tw) ** 2)

    # 조향 변화율 페널티 - 이 모델의 핵심.
    # 시뮬은 서보 지연과 타이어 슬립을 모델링하지 않으므로 보상에서 직접 뺀다
    rate = abs(steer - PREV['steer'])
    if rate > 15:
        reward *= 0.5
    elif rate > 8:
        reward *= 0.8

    # 고속 대각도(스핀 조합) 안전망.
    # 최종 액션 스페이스에서는 발동하지 않는다 - 액션이 이미 보장하기 때문
    if speed > 1.9 and abs(steer) > 15:
        reward *= 0.7

    PREV['steer'] = steer
    return float(max(reward, 1e-3))
