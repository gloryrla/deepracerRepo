"""
[레인 A+] 중앙선 추종 + 워블 억제, 조향 +/-30도까지 확장.

=========================== 왜 이 파일이 있나 ===========================

실차에서 중앙선 방식이 잘 돌았지만 코너에서 속도를 올리면 벗어났다. 조향
권한이 부족해서 언더스티어가 난 것으로 보고 +/-30도 액션과 저속(1.2) 액션을
추가했다. 그런데 기존 보상을 그대로 두면 새 액션이 쓰이지 않는다.

--- 고친 것 1: 새 액션을 죽이던 페널티 ---

기존:  if speed > 1.9 and abs(steer) > 15: reward *= 0.7
       if rate > 15: reward *= 0.5

30도 액션은 이 둘에 동시에 걸려 항상 0.35배를 받는다. 정책은 확실하게 "30도는
쓰면 안 되는 것"을 학습한다. 즉 액션을 추가해도 죽은 액션이 된다.

그래서 두 임계값을 액션 스페이스 폭에 맞춰 넓혔다.
  고속 대각도 판정   15도 -> 25도,  속도 1.9 -> 2.0
  변화율 판정        8/15 -> 14/24

목적이 바뀐 것은 아니다. 막고 싶은 것은 "고속에서 풀 조향"이라는 스핀 조합이고,
+/-30은 액션 스페이스에서 저속(1.2)과 묶어두었으므로 이 판정에 걸리지 않는다.
즉 위험한 조합은 여전히 막으면서, 코너 탈출용 대각도는 허용한다.

--- 고친 것 2: 속도 항이 없어서 기어가는 것이 유리했다 ---

기존 보상에는 속도 항이 아예 없었다. 보상은 스텝마다 더해지는데 느리게 달리면
스텝이 늘어난다. 16.635 m 기준으로

        2.4 m/s -> 104 스텝
        1.2 m/s -> 208 스텝

스텝당 보상이 같으면 1.2로 기어가는 쪽이 총보상을 2배 받는다. 여기에 1.2 액션을
추가하면 정책이 그것만 쓰는 쪽으로 수렴할 위험이 크다.

핵심은 지수다. 보상이 v^p 이고 스텝 수가 1/v 이므로 총보상은 v^(p-1) 이다.

        p = 1.0  ->  v^0     정확히 무차별. 아무 효과가 없다
        p = 1.5  ->  v^0.5   빠른 쪽이 유리          <- 채택
        p = 2.0  ->  v^1     너무 강해 코너 감속을 안 할 위험

**속도 항의 지수는 반드시 1보다 커야 한다.** 1.0으로 두면 스텝 수 증가와 정확히
상쇄되어 아무 일도 일어나지 않는다. 이것이 이 파일에서 가장 중요한 한 줄이다.

p = 1.5에서의 총보상:

        2.4 m/s  속도항 1.000  104스텝  총 104.0
        2.1 m/s  속도항 0.818  119스텝  총  97.4
        1.8 m/s  속도항 0.650  139스텝  총  90.3
        1.2 m/s  속도항 0.354  208스텝  총  73.5

빠른 쪽이 이기지만 격차가 극단적이지 않다. 그리고 탈선은 1e-3이므로 **코너에서
1.2를 쓰는 것이 나가는 것보다 압도적으로 낫다.** 저속 액션을 쓸 이유는 오직
"안 그러면 나간다"일 때뿐이며, 그것이 우리가 원하는 행동이다.

--- 좌표를 쓰지 않는 이유 ---

이 파일에는 좌표가 한 줄도 없다. 전부 track_width 상대값과
distance_from_center 뿐이다. 실차 카메라에 레이턴시가 있으면 절대 좌표 추정이
오염되어 최적경로 추종이 무너진다. distance_from_center는 카메라가 직접 보는
상대량이라 지연에 훨씬 둔감하다. 트랙이 바뀌어도 수정할 것이 없다.

=========================== 설정 ===========================

MAX_SPEED를 액션 스페이스의 최고 속도와 반드시 일치시킨다. 액션 스페이스를
바꾸면 이 값도 바꿔야 한다. 어긋나면 속도 항이 1.0에 도달하지 못하거나
반대로 1.0을 넘어버린다.

권장 액션 스페이스 (10행, 조향 granularity 5 x 속도 granularity 2):

        0/2.4    4/2.4   -4/2.4
       10/2.1  -10/2.1
       18/1.8  -18/1.8
       30/1.2  -30/1.2      <- 코너 탈출: 강한 조향 + 저속
        0/1.9

+/-30을 저속과 묶은 것이 의도다. 고속 대각도는 실차에서 스핀이고, 대각도가
필요한 곳은 어차피 감속해야 하는 헤어핀이다.

--- 튜닝 (한 번에 하나만) ---

    코너에서 아직 벗어난다        -> 1.2 를 1.0 으로 낮춘다
    30도를 안 쓰는 것 같다        -> 고속 대각도 판정을 2.2 / 30 으로 더 넓힌다
    직선에서 굼뜨다               -> 속도 지수를 1.5 -> 1.8
    코너에서 감속을 안 한다       -> 속도 지수를 1.5 -> 1.2
    좌우로 떤다                   -> 변화율 임계값을 10/18 로 좁힌다
    중앙선에 너무 붙어 느리다     -> 4.0 을 3.0 으로 낮춘다

--- PREV 전역에 대한 주의 ---

보상 함수는 이전 스텝을 기억하지 못하므로 조향각을 모듈 전역에 둔다. 롤아웃
워커가 여러 개면 값이 섞일 수 있다. 학습이 이상하게 수렴하면 rate 블록만
삭제하면 된다. 나머지는 그대로 동작한다.
"""
import math

# 액션 스페이스의 최고 속도와 반드시 일치시킬 것
MAX_SPEED = 2.4

# 직전 스텝의 조향각 (변화율 페널티용)
PREV = {'steer': 0.0}


def reward_function(params):
    steer = params['steering_angle']

    # 에피소드 시작 시 이전 에피소드의 잔값을 지운다
    if params['steps'] <= 1:
        PREV['steer'] = steer

    if params['is_offtrack'] or not params['all_wheels_on_track']:
        PREV['steer'] = steer
        return 1e-3

    tw = params['track_width']
    d = params['distance_from_center']
    speed = params['speed']

    # 중앙선까지의 거리. 폭 상대값이므로 트랙이 바뀌어도 유효하다
    reward = math.exp(-4.0 * (d / tw) ** 2)

    # 속도 보상. 지수가 1보다 커야 스텝 수 증가를 이긴다 (상단 주석 참고)
    reward *= (speed / MAX_SPEED) ** 1.5

    # 조향 변화율. ±30 액션이 생겼으므로 임계값을 넓혔다
    rate = abs(steer - PREV['steer'])
    if rate > 24:
        reward *= 0.5
    elif rate > 14:
        reward *= 0.8

    # 고속 풀조향(스핀 조합)만 막는다.
    # ±30은 1.2와 묶여 있어 여기에 걸리지 않는다
    if speed > 2.0 and abs(steer) > 25:
        reward *= 0.7

    PREV['steer'] = steer
    return float(max(reward, 1e-3))
